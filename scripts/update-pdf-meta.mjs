// Generate page counts, print-file sizes, and fast-preview paths for the library.
// Run `npm run update:pdf-meta` after adding or replacing PDFs.
import { readFileSync, readdirSync, statSync, writeFileSync, existsSync } from "node:fs";
import { basename, join } from "node:path";
import { getDocument } from "pdfjs-dist/legacy/build/pdf.mjs";

const root = new URL("..", import.meta.url).pathname;
const pdfDir = join(root, "assets/pdfs");
const previewDir = join(pdfDir, "web");
const metaPath = join(root, "data/pdf-meta.js");
const checkOnly = process.argv.includes("--check");

const files = readdirSync(pdfDir)
  .filter((name) => name.toLowerCase().endsWith(".pdf"))
  .sort((a, b) => a.localeCompare(b, "en"));

const meta = {};
const errors = [];
for (const name of files) {
  const path = join(pdfDir, name);
  try {
    const bytes = readFileSync(path);
    const task = getDocument({ data: new Uint8Array(bytes), disableWorker: true, isEvalSupported: false });
    const doc = await task.promise;
    const previewName = `${name.replace(/\.pdf$/i, "")}-web.pdf`;
    const previewPath = join(previewDir, previewName);
    const entry = { pages: doc.numPages, bytes: statSync(path).size };
    await task.destroy();
    if (existsSync(previewPath)) entry.webFile = `pdfs/web/${previewName}`;
    meta[`pdfs/${name}`] = entry;
  } catch (error) {
    errors.push(`${name}: ${error.message}`);
  }
}

if (errors.length) {
  console.error("Could not read these PDFs:\n" + errors.map((line) => ` - ${line}`).join("\n"));
  process.exit(1);
}

const body = Object.keys(meta)
  .sort((a, b) => a.localeCompare(b, "en"))
  .map((key) => `  ${JSON.stringify(key)}: ${JSON.stringify(meta[key])}`)
  .join(",\n");
const output = `// Generated by scripts/update-pdf-meta.mjs. Do not edit by hand.\nwindow.BOBBER_PDF_META = {\n${body}\n};\n`;
const current = existsSync(metaPath) ? readFileSync(metaPath, "utf8") : "";

if (checkOnly) {
  if (current !== output) {
    console.error("data/pdf-meta.js is out of date. Run: npm run update:pdf-meta");
    process.exit(1);
  }
  console.log(`PDF metadata is current: ${Object.keys(meta).length} files.`);
} else {
  writeFileSync(metaPath, output);
  const total = Object.values(meta).reduce((sum, entry) => sum + entry.bytes, 0);
  console.log(`Wrote ${Object.keys(meta).length} PDF records (${(total / 1048576).toFixed(1)} MB print files).`);
}
